"""紧急红线（法律域）：人身安全 > 证据安全 > 时效安全。

与医疗版同构的规则短路设计，但法律场景的三类红线有明确优先级：
① 人身安全正在受威胁 → 立即报警，法律问题全部靠后；
② 证据面临灭失 → 立即固定证据（截图/公证/保全）；
③ 时效临界的表述 → 强制走 calc_limitation 精确计算。
规则层宁可误报不可漏报（如"上次被打"也命中——追问澄清即可，
漏报的代价是真实的人身伤害）。
"""

from __future__ import annotations

import re

RED_FLAG_PATTERNS: list[tuple[str, str]] = [
    # ① 人身安全（最高优先级）
    (r"正在被打|又在打|他打我|她打我|家暴|家庭暴力", "家暴/暴力"),
    (r"跟踪我|尾随|盯着我|监视我", "跟踪骚扰"),
    (r"威胁(我|要)|扬言|恐吓|要杀|同归于尽", "威胁恐吓"),
    (r"限制(我)?(的)?人身自由|不让我走|拘禁", "非法拘禁"),
    (r"抢(我|孩子|手机)|抢走", "抢夺"),
    # ② 证据安全
    (r"(要|想|准备|打算)(删|删除|销毁|毁掉|改)(记录|聊天|证据|借条|合同)", "证据灭失风险"),
    (r"不认(账|借条|欠条)|翻供|改口", "对方否认风险"),
    # ③ 时效临界
    (r"快(要)?(三年|3年)|马上过时效|马上到期|就快过期|差(不)多三年", "时效临界"),
]

_EMERGENCY_REPLY_TEMPLATES = {
    "家暴/暴力": ("您描述的情况涉及正在发生的人身安全威胁。请立即拨打 110 报警；"
               "如系家庭暴力，可同时向法院申请人身安全保护令（可就近到法院立案窗口，"
               "情况紧急的可口头申请）。人身安全优先于一切法律程序。"),
    "跟踪骚扰": ("您描述的情况涉及人身安全。建议立即拨打 110，并尽量停留在有监控、"
               "有他人的公共场所；保留跟踪证据（照片、录像、通话记录）。"),
    "威胁恐吓": ("遭遇威胁恐吓请立即报警（110）。保留聊天记录、通话录音等证据，"
               "不要删除；威胁内容涉及人身安全的，警方可先行处置。"),
    "非法拘禁": ("您或他人人身自由受限属于紧急情况，请立即拨打 110。"),
    "抢夺": ("涉及人身与财物抢夺，请立即拨打 110；财物纠纷后续再通过法律途径解决。"),
}
_EVIDENCE_REPLY = ("对方可能销毁/否认关键证据。请立即固定证据：聊天记录截图并备份原载体、"
                   "借条合同拍照留存、重要证据可申请公证或向法院申请证据保全。"
                   "证据固定完成前不要打草惊蛇。")
_LIMITATION_REPLY = ("您提到的时间可能接近诉讼时效（一般为三年，自权利受损且知道之日起算）。"
                     "请提供具体日期，我用时效计算工具精确核算剩余天数；"
                     "时效临近可通过催告、对方部分还款、起诉等方式中断重算。")


def detect_red_flags(text: str) -> list[str]:
    hits: list[str] = []
    for pattern, name in RED_FLAG_PATTERNS:
        if re.search(pattern, text):
            hits.append(name)
    return hits


def emergency_reply(flags: list[str]) -> str:
    """按优先级生成应答：人身安全 > 证据 > 时效。"""
    for flag, reply in _EMERGENCY_REPLY_TEMPLATES.items():
        if flag in flags:
            return reply
    if "证据灭失风险" in flags or "对方否认风险" in flags:
        return _EVIDENCE_REPLY
    if "时效临界" in flags:
        return _LIMITATION_REPLY
    return "您描述的情况较为紧急，建议尽快咨询律师或拨打12348法律援助热线。"
